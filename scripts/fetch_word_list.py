"""Fetch Word Sprint's word list from the Datamuse API and write Frontend/frontend/words.ts.

Run by hand when the list should change; the game never calls the API itself (the site's
Content-Security-Policy only allows same-origin requests, and the arcade must work offline).

    uv run --no-project python scripts/fetch_word_list.py

For each length from 4 to 8 letters it asks Datamuse for words matching that many wildcards,
keeps plain lowercase words, prefers the most frequent, drops a small blocklist, and writes the
uppercase result. Review the generated file before committing it.
"""
from __future__ import annotations

import json
import re
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://api.datamuse.com/words"
LENGTHS = range(4, 9)
PER_LENGTH = 100
OUTPUT = Path(__file__).resolve().parents[1] / "Frontend" / "frontend" / "words.ts"
WORD = re.compile(r"^[a-z]+$")
# Words that are unpleasant, easily misread, or not words a player expects to type.
BLOCKLIST = frozenset({
    "anal", "anus", "arse", "bitch", "bitches", "boob", "boobs", "butt", "cock", "crap", "damn", "dick",
    "dildo", "drug", "drugs", "dumb", "fart", "fuck", "fucked", "fucker", "fucking", "gay", "hell", "homo",
    "kill", "killed", "killer", "killing", "kills", "nazi", "nazis", "nude", "nudes", "orgy", "penis", "piss",
    "porn", "porno", "pussy", "rape", "raped", "rapist", "retard", "sex", "sexy", "shit", "slut", "suicide",
    "tits", "twat", "vagina", "whore", "dead", "death", "murder", "murdered", "abuse", "abused", "terror",
    "bomb", "bombs", "weapon", "weapons", "shoot", "shooting", "gun", "guns", "blood", "bloody",
})


def query(pattern: str) -> list[dict[str, object]]:
    # md=fp adds a frequency tag (f:<per million>) and parts of speech (prop marks proper nouns).
    params = urllib.parse.urlencode({"sp": pattern, "md": "fp", "max": 1000})
    request = urllib.request.Request(f"{API}?{params}", headers={"User-Agent": "inquisitor-word-list/1"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def frequency(row: dict[str, object]) -> float:
    for tag in row.get("tags", []) or []:
        if isinstance(tag, str) and tag.startswith("f:"):
            return float(tag[2:])
    return 0.0


def common_word(row: dict[str, object]) -> bool:
    word, tags = row.get("word"), row.get("tags") or []
    return (
        isinstance(word, str)
        and WORD.match(word) is not None
        and word not in BLOCKLIST
        and "prop" not in tags
        # Words with no part of speech are mostly abbreviations and fragments.
        and any(tag in tags for tag in ("n", "v", "adj", "adv"))
    )


def fetch(length: int) -> list[str]:
    # One query per first letter: a wildcard-only query returns an alphabetical slice, not the
    # most common words across the alphabet.
    rows: dict[str, float] = {}
    for letter in "abcdefghijklmnopqrstuvwxyz":
        for row in query(letter + "?" * (length - 1)):
            if common_word(row):
                rows[str(row["word"])] = frequency(row)
    ranked = sorted(rows, key=lambda word: rows[word], reverse=True)
    return ranked[:PER_LENGTH]


def main() -> None:
    words: list[str] = []
    for length in LENGTHS:
        found = fetch(length)
        print(f"{length} letters: {len(found)} words")
        words.extend(word.upper() for word in found)
    words = sorted(dict.fromkeys(words))
    lines = ",\n".join(f'  "{word}"' for word in words)
    OUTPUT.write_text(
        "// Generated by scripts/fetch_word_list.py from the Datamuse API (https://www.datamuse.com/api/).\n"
        "// Do not edit by hand; rerun the script and review the result instead.\n"
        f"export const WORDS: readonly string[] = [\n{lines},\n];\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {len(words)} words to {OUTPUT}")


if __name__ == "__main__":
    main()
